// Planner domain.
// Turns logged spending into a per-pay-period plan: what each kind of cost
// usually comes to, how much is allocated to each pot ("gullak"), and what
// that leaves to save. Everything here is arithmetic on app state plus one
// stored plan object (settings.planner) — no ledger rows are ever written.

import { todayStr } from "../lib/index.js";
import { SAVINGS_CAT } from "../categories/index.js";
import { cycleStartDay, currentPeriodKey, periodStartStr, periodEndStr, txInRange } from "../periods/index.js";
import { installmentRemaining } from "../recurring/index.js";
import { windowPeriodKeys } from "../health/index.js";

// The built-in pots. `fixed` marks costs set by someone else (a lender, a
// utility) — they never get a pace colour, since "you're spending this too
// fast" means nothing for a direct debit.
export const DEFAULT_POTS = [
  { id: "bills", label: "Bills & mortgage", fixed: true },
  { id: "emis", label: "EMIs", fixed: true },
  { id: "groceries", label: "Groceries" },
  { id: "flexible", label: "Shopping & eating out" },
  { id: "commute", label: "Commute" },
  { id: "house", label: "House maintenance" },
  { id: "car", label: "Car maintenance" },
  { id: "other", label: "Everything else" }
];

export const BUCKET_IDS = DEFAULT_POTS.map(function (p) { return p.id; });

export const POT_TYPES = [
  { id: "expense", label: "Expense" },
  { id: "savings", label: "Savings" },
  { id: "future", label: "Future plan" }
];

export const DEFAULT_THRESHOLDS = { green: 500, amber: 200 };
export const WINDOW_OPTIONS = [3, 6];

// How far ahead of the calendar a pot's spending can run before it turns
// amber — without some slack a single weekly shop on day two would do it.
export const PACE_MARGIN = 0.15;

var DEFAULT_BY_ID = {};
DEFAULT_POTS.forEach(function (p) { DEFAULT_BY_ID[p.id] = p; });

function round2(n) { return Math.round(n * 100) / 100; }

function moneyOrNull(v) {
  if (v === null || v === undefined || v === "") return null;
  var n = Number(v);
  return isFinite(n) && n >= 0 ? round2(n) : null;
}

function cleanText(v, max) { return String(v == null ? "" : v).trim().slice(0, max); }

// ---------- which bucket a transaction belongs to ----------

// Anything generated by a recurring rule is a fixed commitment whatever its
// category (a gym direct debit is a bill, not "health") — an instalment rule
// is an EMI, every other rule is a bill. A rule deleted since still counts as
// a bill. Savings transfers aren't spending and belong to no bucket.
//
// `links` maps a recurring rule's id to the pot the user tied it to (see
// planLinks) — that rule's payments then belong to that pot alone, so a pot
// added for one direct debit doesn't leave the same money counted in bills.
export function bucketForTx(t, rulesById, links) {
  if (t.categoryId === SAVINGS_CAT) return null;
  if (t.recurringId) {
    if (links && links[t.recurringId]) return links[t.recurringId];
    var rule = rulesById && rulesById[t.recurringId];
    return rule && rule.installment ? "emis" : "bills";
  }
  switch (t.categoryId) {
    case "housing":
      if (t.subcategoryId === "emi") return "emis";
      if (t.subcategoryId === "house_maintenance") return "house";
      return t.subcategoryId ? "other" : "bills";
    case "bills":
    case "insurance":
      return "bills";
    case "groceries":
      return "groceries";
    case "shopping":
    case "eating_out":
    case "entertainment":
      return "flexible";
    case "transport":
      return "commute";
    case "car":
      return t.subcategoryId === "fuel" || t.subcategoryId === "parking" ? "commute" : "car";
    default:
      return "other";
  }
}

function rulesIndex(rules) {
  var out = {};
  (rules || []).forEach(function (r) { out[r.id] = r; });
  return out;
}

function bucketKeys(links) {
  var keys = BUCKET_IDS.slice();
  Object.keys(links || {}).forEach(function (rid) { if (keys.indexOf(links[rid]) === -1) keys.push(links[rid]); });
  return keys;
}

function emptyTotals(links) {
  var out = {};
  bucketKeys(links).forEach(function (id) { out[id] = 0; });
  return out;
}

function addToBuckets(totals, txs, rulesById, links, skipRecurring) {
  txs.forEach(function (t) {
    if (skipRecurring && t.recurringId) return;
    var b = bucketForTx(t, rulesById, links);
    if (b) totals[b] += t.amount;
  });
  return totals;
}

// Which pot each linked recurring rule belongs to: { ruleId: potId }.
export function planLinks(plan) {
  var out = {};
  plan.pots.forEach(function (p) { if (p.recurringId && !out[p.recurringId]) out[p.recurringId] = p.id; });
  return out;
}

// What the active recurring rules will take this month — the same reading as
// Financial health's "fixed commitments", split into bills and EMIs.
export function fixedCommitments(st, now, links) {
  var curMonth = todayStr(now).slice(0, 7);
  var out = { bills: 0, emis: 0 };
  (st.recurringExpenses || []).forEach(function (r) {
    if (!r.active || (r.startMonth && r.startMonth > curMonth)) return;
    var amount = r.amount;
    if (r.installment) {
      var remaining = installmentRemaining(r, st.transactions || []);
      if (!(remaining > 0)) return;
      amount = Math.min(r.amount, remaining);
    }
    var key = (links && links[r.id]) || (r.installment ? "emis" : "bills");
    out[key] = (out[key] || 0) + amount;
  });
  return out;
}

// Typical spend per pay period for each bucket, in whole pounds. Hand-logged
// spending is averaged over the last `count` complete periods that have any
// history behind them; recurring rules are read at today's amounts instead,
// because last quarter's average of a direct debit that has since changed
// (or ended) is simply the wrong number to plan against.
export function bucketAverages(st, count, now, links) {
  now = now || new Date();
  var startDay = cycleStartDay(st.incomeSources);
  var txs = st.transactions || [];
  var first = txs.reduce(function (min, t) { return !min || t.date < min ? t.date : min; }, null);
  var keys = windowPeriodKeys({ count: count }, startDay, now).filter(function (mk) {
    return first && periodEndStr(mk, startDay) > first;
  });
  var rulesById = rulesIndex(st.recurringExpenses);
  var totals = emptyTotals(links);
  keys.forEach(function (mk) {
    addToBuckets(totals, txInRange(txs, periodStartStr(mk, startDay), periodEndStr(mk, startDay)), rulesById, links, true);
  });
  var fixed = fixedCommitments(st, now, links);
  var averages = {};
  bucketKeys(links).forEach(function (id) {
    averages[id] = Math.round((keys.length ? totals[id] / keys.length : 0) + (fixed[id] || 0));
  });
  return { averages: averages, periodsUsed: keys.length };
}

// Spend so far in the current pay period, per bucket, plus how far through
// the period today is.
export function currentPeriodActuals(st, now, links) {
  now = now || new Date();
  var startDay = cycleStartDay(st.incomeSources);
  var key = currentPeriodKey(startDay, now);
  var start = periodStartStr(key, startDay);
  var end = periodEndStr(key, startDay);
  var spent = addToBuckets(emptyTotals(links), txInRange(st.transactions || [], start, end), rulesIndex(st.recurringExpenses), links, false);
  Object.keys(spent).forEach(function (id) { spent[id] = round2(spent[id]); });
  var dayMs = 86400000;
  var startD = new Date(start + "T00:00:00");
  var endD = new Date(end + "T00:00:00");
  var today0 = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  var totalDays = Math.max(1, Math.round((endD - startD) / dayMs));
  var daysLeft = Math.max(0, Math.round((endD - today0) / dayMs));
  return {
    key: key,
    spent: spent,
    totalDays: totalDays,
    daysLeft: daysLeft,
    elapsed: Math.min(1, Math.max(0, (totalDays - daysLeft + 1) / totalDays))
  };
}

// ---------- the stored plan ----------

// The plan comes from a jsonb column the user edits, so anything missing or
// malformed falls back to the defaults. Built-in pots always exist, in their
// fixed order; pots the user added follow in the order they were added.
// An added expense pot can carry `recurringId`, tying it to one direct debit:
// it then has ledger figures of its own (its bucket is its own id) and is a
// fixed cost. Without that it is a plan-only amount with no bucket.
export function normalisePlan(raw) {
  raw = raw && typeof raw === "object" ? raw : {};
  var stored = Array.isArray(raw.pots) ? raw.pots.filter(function (p) { return p && typeof p === "object" && p.id; }) : [];
  var storedById = {};
  stored.forEach(function (p) { storedById[p.id] = p; });

  var pots = DEFAULT_POTS.map(function (def) {
    var s = storedById[def.id] || {};
    return {
      id: def.id,
      label: cleanText(s.label, 40) || def.label,
      type: "expense",
      bucket: def.id,
      fixed: !!def.fixed,
      recurringId: null,
      estimate: moneyOrNull(s.estimate),
      amount: moneyOrNull(s.amount),
      account: cleanText(s.account, 40)
    };
  });
  var seen = {};
  stored.forEach(function (s) {
    var id = String(s.id);
    if (DEFAULT_BY_ID[id] || seen[id]) return;
    var label = cleanText(s.label, 40);
    if (!label) return;
    seen[id] = true;
    var type = POT_TYPES.some(function (t) { return t.id === s.type; }) ? s.type : "expense";
    var recurringId = type === "expense" && s.recurringId ? String(s.recurringId) : null;
    pots.push({
      id: id,
      label: label,
      type: type,
      bucket: recurringId ? id : null,
      fixed: !!recurringId,
      recurringId: recurringId,
      estimate: null,
      amount: moneyOrNull(s.amount),
      account: cleanText(s.account, 40)
    });
  });

  var th = raw.thresholds || {};
  var green = moneyOrNull(th.green);
  var amber = moneyOrNull(th.amber);
  var thresholds = validThresholds(green, amber)
    ? { green: green, amber: amber }
    : { green: DEFAULT_THRESHOLDS.green, amber: DEFAULT_THRESHOLDS.amber };

  var sv = raw.savings || {};
  return {
    window: WINDOW_OPTIONS.indexOf(Number(raw.window)) !== -1 ? Number(raw.window) : WINDOW_OPTIONS[0],
    thresholds: thresholds,
    savings: { label: cleanText(sv.label, 40) || "Savings", account: cleanText(sv.account, 40) },
    pots: pots
  };
}

export function validThresholds(green, amber) {
  return typeof green === "number" && typeof amber === "number" && isFinite(green) && isFinite(amber) && amber >= 0 && green >= amber;
}

// Fills in the two numbers each pot can leave blank: the line-item estimate
// defaults to the calculated average, and the allocation defaults to the
// estimate — so a brand-new plan is already a complete one.
export function resolvePots(plan, averages) {
  return plan.pots.map(function (p) {
    var average = p.bucket ? averages[p.bucket] || 0 : null;
    var estimate = p.bucket ? (p.estimate != null ? p.estimate : average) : null;
    var amount = p.amount != null ? p.amount : estimate != null ? estimate : 0;
    return {
      id: p.id, label: p.label, type: p.type, bucket: p.bucket, fixed: p.fixed, account: p.account,
      recurringId: p.recurringId, builtIn: !!DEFAULT_BY_ID[p.id],
      average: average,
      estimate: estimate,
      estimateEdited: p.estimate != null,
      amount: amount,
      amountEdited: p.amount != null
    };
  });
}

// ---------- colours ----------

// A pot tracked against the ledger is red once more has been spent than it
// holds, amber while spending is running ahead of the days gone by (so it
// will run dry before payday at this rate), green otherwise. Fixed costs and
// pots with no ledger behind them (the ones the user added) stay neutral.
export function potStatus(pot, spent, elapsed) {
  if (pot.type !== "expense" || pot.fixed || !pot.bucket) return "neutral";
  if (spent > pot.amount) return "red";
  if (!(spent > 0)) return "green";
  return spent / pot.amount > elapsed + PACE_MARGIN ? "amber" : "green";
}

// Expense pots come off income; savings and future-plan pots are money being
// kept, so they count towards the total saved rather than against it.
// `unassigned` is what's saved but not yet given a named pot — negative when
// the named pots promise more than is actually left.
export function savingsSummary(income, pots, thresholds) {
  var expenses = 0;
  var named = 0;
  pots.forEach(function (p) {
    if (p.type === "expense") expenses += p.amount; else named += p.amount;
  });
  var out = { expenses: round2(expenses), named: round2(named), total: null, unassigned: null, status: "neutral" };
  if (income == null || !(income > 0)) return out;
  out.total = round2(income - expenses);
  out.unassigned = round2(out.total - named);
  out.status = out.total >= thresholds.green ? "green" : out.total >= thresholds.amber ? "amber" : "red";
  return out;
}

// When savings fall short of green: by how much, and the adjustable pot most
// worth looking at — the one furthest above its own average, or failing
// that simply the largest.
export function savingsNudge(summary, pots, thresholds) {
  if (summary.total == null || summary.status === "green") return null;
  var adjustable = pots.filter(function (p) { return p.type === "expense" && !p.fixed && p.amount > 0; });
  var above = adjustable.filter(function (p) { return p.average != null && p.amount > p.average; })
    .sort(function (a, b) { return (b.amount - b.average) - (a.amount - a.average); })[0];
  var biggest = adjustable.slice().sort(function (a, b) { return b.amount - a.amount; })[0];
  var pick = above || biggest || null;
  return {
    shortfall: round2(thresholds.green - summary.total),
    target: thresholds.green,
    pot: pick ? { label: pick.label, amount: pick.amount, overAverage: above ? round2(above.amount - above.average) : 0 } : null
  };
}

// What to move on payday, grouped by the account each pot is parked in.
// Pots with no account, or nothing allocated, aren't a transfer.
export function transferList(pots, plan, summary) {
  var rows = pots.map(function (p) { return { label: p.label, account: p.account, amount: p.amount }; });
  if (summary && summary.unassigned > 0) {
    rows.push({ label: plan.savings.label, account: plan.savings.account, amount: summary.unassigned });
  }
  var byKey = {};
  var order = [];
  rows.forEach(function (r) {
    if (!r.account || !(r.amount > 0)) return;
    var key = r.account.toLowerCase();
    if (!byKey[key]) { byKey[key] = { account: r.account, total: 0, pots: [] }; order.push(key); }
    byKey[key].total = round2(byKey[key].total + r.amount);
    byKey[key].pots.push({ label: r.label, amount: r.amount });
  });
  return order.map(function (k) { return byKey[k]; });
}

// ---------- everything the view needs, in one call ----------

export function computePlanner(st, rawPlan, now) {
  now = now || new Date();
  var plan = normalisePlan(rawPlan);
  var links = planLinks(plan);
  var avg = bucketAverages(st, plan.window, now, links);
  var actuals = currentPeriodActuals(st, now, links);
  var pots = resolvePots(plan, avg.averages).map(function (p) {
    p.spent = p.bucket ? actuals.spent[p.bucket] : null;
    p.left = p.bucket ? round2(p.amount - p.spent) : null;
    p.status = potStatus(p, p.spent || 0, actuals.elapsed);
    return p;
  });
  var summary = savingsSummary(st.income, pots, plan.thresholds);
  return {
    plan: plan,
    periodsUsed: avg.periodsUsed,
    period: { key: actuals.key, daysLeft: actuals.daysLeft, totalDays: actuals.totalDays, elapsed: actuals.elapsed },
    pots: pots,
    summary: summary,
    nudge: savingsNudge(summary, pots, plan.thresholds),
    transfers: transferList(pots, plan, summary)
  };
}
